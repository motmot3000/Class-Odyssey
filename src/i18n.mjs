export function setLang(next) {
  lang = next === "en" ? "en" : "fr";
  if (typeof document !== "undefined") {
    document.documentElement.lang = lang;
    const label = document.getElementById("current-lang");
    // The control shows the language it switches TO, next to that country's
    // small flag, so the intent is obvious at a glance.
    if (label) label.textContent = lang === "fr" ? "EN" : "FR";
    const toggle = document.getElementById("lang-toggle");
    toggle?.setAttribute("aria-label", lang === "fr" ? "Passer en anglais" : "Switch to French");
    toggle?.setAttribute("title", lang === "fr" ? "Passer en anglais (English)" : "Switch to French (Français)");
    try { localStorage.setItem(LANGUAGE_KEY, lang); } catch { /* private browsing */ }
  }
}

export function initLanguage() {
  let initial = "fr";
  try { initial = localStorage.getItem(LANGUAGE_KEY) || document.documentElement.lang || initial; } catch { /* storage unavailable */ }
  setLang(initial);
}

export function getLang() {
  return lang;
}

export function t(key, params = {}) {
  /* English is the source language: an unknown key IS its English copy, so EN
   * must never fall back to the French-only maps. French falls back through
   * the shared [fr, en] arrays, then the French messages, then the EN copy. */
  const index = lang === "fr" ? 0 : 1;
  const text = dict[lang][key] ?? messages[key]?.[index]
    ?? (lang === "fr" ? dict.fr[key] ?? frenchMessages[key] : key)
    ?? key;
  return text.replace(/\{(\w+)\}/g, (placeholder, name) => Object.hasOwn(params, name) ? String(params[name]) : placeholder);
}

export function hasTranslation(key, language = lang) {
  return Object.hasOwn(dict[language], key) || Object.hasOwn(messages, key);
}

/* The three classroom-rule lists are account data now, but an existing account
 * must keep the current copy. Derive that seed from the shared FR/EN dictionary
 * so both languages are preserved and one source stays authoritative. */
export function defaultRules() {
  const pair = (key) => ({ fr: dict.fr[key] ?? "", en: dict.en[key] ?? "" });
  return {
    journey: Array.from({ length: 7 }, (_, index) => pair(`rules.game.${index}`)),
    xp: Array.from({ length: 2 }, (_, index) => pair(`rules.xp.${index}`)),
    money: Array.from({ length: 2 }, (_, index) => pair(`rules.money.${index}`))
  };
}

export function translateMessage(message = "") {
  if (lang !== "fr") return message;
  if (Object.hasOwn(frenchMessages, message)) return frenchMessages[message];
  let match = message.match(/^the password needs at least (\d+) characters\.?$/i);
  if (match) return `Le mot de passe doit contenir au moins ${match[1]} caractères.`;
  match = message.match(/^The password cannot be longer than (\d+) characters\.$/);
  if (match) return `Le mot de passe ne doit pas dépasser ${match[1]} caractères.`;
  match = message.match(/^Too many tries\. Wait (\d+) minutes? and try again\.$/);
  if (match) return `Trop de tentatives. Attends ${match[1]} minute(s) et réessaie.`;
  match = message.match(/^an email address is required$/i);
  if (match) return "Une adresse e-mail est requise.";
  match = message.match(/^the email address is not valid$/i);
  if (match) return "L’adresse e-mail n’est pas valide.";
  match = message.match(/^the email address is too long$/i);
  if (match) return "L’adresse e-mail est trop longue.";
  return message;
}

/* Domain strings remain canonical English; presentation selects a translation. */
export function tItem(item, field) {
  if (lang === "fr") {
    const key = `domain.${item.id}.${field}`;
    if (hasTranslation(key, "fr")) return t(key);
  }
  return item[field];
}
